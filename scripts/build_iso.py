#!/usr/bin/env python3
"""
Build js/iso.js: every ISO 3166-1 country and region (249), with its alpha-3 code,
an everyday English name, aliases for matching folder labels, and a continent.

    python3 scripts/build_iso.py ISO_CSV

ISO_CSV is all.csv from github.com/lukes/ISO-3166-Countries-with-Regional-Codes
(ISO codes with UN M49 regions). Continents follow the usual seven:
the Americas split at the South America sub-region; Antarctica takes ATA plus
the sub-Antarctic territories BVT, SGS, HMD and ATF; Taiwan (no M49 region) is Asia.
"""
import csv, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANTARCTICA = {"ATA", "BVT", "SGS", "HMD", "ATF"}

# everyday names for formal ISO ones
COMMON = {
    "GBR": "United Kingdom", "USA": "United States", "KOR": "South Korea", "PRK": "North Korea",
    "TWN": "Taiwan", "VAT": "Vatican City", "RUS": "Russia", "IRN": "Iran", "SYR": "Syria",
    "LAO": "Laos", "VNM": "Vietnam", "BOL": "Bolivia", "VEN": "Venezuela", "TZA": "Tanzania",
    "MDA": "Moldova", "PSE": "Palestine", "FSM": "Micronesia", "COD": "DR Congo", "COG": "Republic of the Congo",
    "BRN": "Brunei", "NLD": "Netherlands", "FLK": "Falkland Islands", "VGB": "British Virgin Islands",
    "VIR": "U.S. Virgin Islands", "MAF": "Saint Martin", "SXM": "Sint Maarten", "MAC": "Macau",
    "UMI": "U.S. Minor Outlying Islands", "BES": "Caribbean Netherlands", "SHN": "Saint Helena",
    "IOT": "British Indian Ocean Territory", "CIV": "Côte d'Ivoire", "CPV": "Cape Verde",
}
ALIASES = {
    "GBR": ["UK", "Great Britain", "Britain", "England", "Scotland", "Wales", "Northern Ireland"],
    "USA": ["US", "USA", "United States of America", "America"], "TUR": ["Turkey", "Türkiye"],
    "CZE": ["Czech Republic"], "VAT": ["Vatican", "Holy See"], "CIV": ["Ivory Coast"], "MMR": ["Burma"],
    "TLS": ["East Timor"], "SWZ": ["Swaziland"], "MKD": ["Macedonia"], "NLD": ["Holland"],
    "HKG": ["Hong Kong SAR"], "MAC": ["Macao", "Macau SAR"], "KOR": ["Korea"], "COD": ["Congo-Kinshasa"],
    "COG": ["Congo", "Congo-Brazzaville"], "PSE": ["State of Palestine"], "ALA": ["Aland Islands"],
}

def continent(r):
    a = r["alpha-3"]
    if a in ANTARCTICA: return "Antarctica"
    if a == "TWN": return "Asia"
    if r["region"] == "Americas":
        return "South America" if r["intermediate-region"] == "South America" else "North America"
    return r["region"]

def everyday(r):
    a, n = r["alpha-3"], r["name"]
    if a in COMMON: return COMMON[a]
    n = re.sub(r"\s*\(.*?\)", "", n)                # Falkland Islands (Malvinas) -> Falkland Islands
    return n

def main():
    rows = list(csv.DictReader(open(Path(sys.argv[1]).expanduser(), encoding="utf-8")))
    assert len(rows) == 249, len(rows)
    out = []
    for r in sorted(rows, key=lambda r: r["alpha-3"]):
        name = everyday(r)
        aliases = sorted({r["name"], *ALIASES.get(r["alpha-3"], [])} - {name})
        out.append([r["alpha-3"], name, continent(r), aliases])
    totals = {}
    for a, n, c, _ in out: totals[c] = totals.get(c, 0) + 1
    assert sum(totals.values()) == 249
    lines = ["// GENERATED by scripts/build_iso.py from ISO 3166-1 with UN M49 regions — do not edit.",
             "// [alpha-3, everyday name, continent, aliases]. 249 countries and regions.",
             "const ISO = ["]
    lines += ["  " + json.dumps(e, ensure_ascii=False, separators=(",", ":")) + "," for e in out]
    lines.append("];")
    (ROOT / "js" / "iso.js").write_text("\n".join(lines) + "\n")
    print("wrote js/iso.js:", len(out), "entries;", dict(sorted(totals.items(), key=lambda kv: -kv[1])))

if __name__ == "__main__":
    main()
